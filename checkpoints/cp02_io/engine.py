_font_cache = {}


def _font(size):
    if size not in _font_cache:
        _font_cache[size] = pygame.font.SysFont("consolas,couriernew,monospace", size)
    return _font_cache[size]


def draw_text(surface, text, pos, size=18, color=(198, 216, 232), anchor="topleft"):
    """Draw a line of text.  anchor can be 'topleft', 'center', 'midtop', etc."""
    img = _font(size).render(str(text), True, color)
    rect = img.get_rect()
    setattr(rect, anchor, (int(pos[0]), int(pos[1])))
    surface.blit(img, rect)
    return rect


def draw_glow(surface, pos, radius, color):
    """A soft additive glow - the look of everything alive down here."""
    x, y = int(pos[0]), int(pos[1])
    radius = max(2, int(radius))
    layers = 6
    for i in range(layers, 0, -1):
        r = max(1, int(radius * i / layers))
        a = int(70 * (1 - i / (layers + 1)))
        blob = pygame.Surface((r * 2, r * 2), pygame.SRCALPHA)
        pygame.draw.circle(blob, (color[0], color[1], color[2], a), (r, r), r)
        surface.blit(blob, (x - r, y - r), special_flags=pygame.BLEND_ADD)


def draw_ring(surface, pos, radius, color=(90, 170, 200), width=2):
    """Draw a circle outline (not filled) centered at pos with the given
    radius - handy for sonar-style rings drawn with a loop."""
    pygame.draw.circle(surface, color, (int(pos[0]), int(pos[1])), max(1, int(radius)), width)


def _hud_surface():
    if _state.hud_surface is None:
        _state.hud_surface = pygame.Surface((WIDTH, HEIGHT), pygame.SRCALPHA)
    return _state.hud_surface


def draw_hud_text(text, pos, size=16, color=(198, 216, 232), anchor="topleft"):
    """Draw a line of dashboard text that stays visible no matter how dark or
    deep you are - like an instrument on the cockpit panel, not a light shining
    into the water. Use this instead of draw_text for status readouts inside
    frame(); use draw_text for anything that should be hidden by the dark."""
    draw_text(_hud_surface(), text, pos, size=size, color=color, anchor=anchor)


def world_y_to_screen(sub, world_depth):
    """Convert a depth in meters to a y pixel, given where the sub is now."""
    return int(SUB_SCREEN_Y + (world_depth - sub.depth) * PIXELS_PER_METER)


def world_x_to_screen(sub, world_x):
    """Convert a horizontal world position to an x pixel, given where the sub
    is now. Not used by anything yet - here for Module 7, when creatures get
    a fixed (x, y) position in the world and need to scroll past like
    everything else does as the sub moves."""
    return int(WIDTH // 2 + (world_x - sub.x))


def distance_to_base_edge(sub):
    """How far outside the recharge base's edge the sub currently is, in
    meters - straight-line distance to (base_x, base_depth), minus
    base_radius. 0 or negative once inside; you don't need to land on an
    exact point, just get within the circle."""
    dx = sub.x - sub.base_x
    dy = sub.depth - sub.base_depth
    return (dx * dx + dy * dy) ** 0.5 - sub.base_radius


def depth_zone_name(depth):
    """Rough name for the water at this depth (you build the real version in Module 9)."""
    if depth < 200:
        return "SUNLIT"
    if depth < 1000:
        return "TWILIGHT"
    if depth < 4000:
        return "MIDNIGHT"
    return "ABYSSAL"


