# System simulation the engine runs for you
# ---------------------------------------------------------------------------
def _update_systems(sub):
    d = _state.dt
    if not sub.alive:
        return
    if sub.descending:
        sub.depth += sub.dive_rate * d
    if sub.ascending:
        sub.depth = max(0.0, sub.depth - sub.rise_rate * d)
    if sub.moving_left:
        sub.x -= sub.drift_speed * d
        sub.total_drift += sub.drift_speed * d
    if sub.moving_right:
        sub.x += sub.drift_speed * d
        sub.total_drift += sub.drift_speed * d
    sub.descending = False          # must be re-requested every frame
    sub.ascending = False
    sub.moving_left = False
    sub.moving_right = False

    if distance_to_base_edge(sub) <= 0:
        sub.oxygen = min(100.0, sub.oxygen + 8.0 * d)      # inside the recharge base - refill
        sub.power = min(100.0, sub.power + 6.0 * d)
    else:
        sub.oxygen = max(0.0, sub.oxygen - (0.55 + sub.depth / 5000.0) * d)
        if sub.light_on and sub.power > 0:
            sub.power = max(0.0, sub.power - 0.45 * d)
    if sub.power <= 0:
        sub.light_on = False
    if sub.depth > sub.rated_depth:
        sub.hull = max(0.0, sub.hull - (sub.depth - sub.rated_depth) * 0.02 * d)
    if sub.oxygen <= 0 or sub.hull <= 0:
        sub.alive = False


