def _pump_events():
    global _pressed
    _pressed = set()
    running = True
    for e in pygame.event.get():
        if e.type == pygame.QUIT:
            running = False
        elif e.type == pygame.KEYDOWN:
            if e.key == pygame.K_ESCAPE:
                running = False
            _held.add(e.key)
            _pressed.add(e.key)
        elif e.type == pygame.KEYUP:
            _held.discard(e.key)
    return running


def show_briefing(pilot, target_depth, ballast_kg, battery_pct):
    """Open a small window that displays the dive plan your Module 2 code built.
    Does nothing in headless mode.  Press ESC or close the window to continue."""
    if HEADLESS:
        return
    pygame.init()
    screen = pygame.display.set_mode((WIDTH, HEIGHT))
    pygame.display.set_caption(f"LUMEN - pre-dive briefing   [engine {ENGINE_VERSION}]")
    clock = pygame.time.Clock()
    lines = [
        ("PRE-DIVE BRIEFING", 30, (220, 235, 245)),
        (f"pilot            {pilot}", 20, (190, 210, 224)),
        (f"target depth     {target_depth} m", 20, (190, 210, 224)),
        (f"ballast          {ballast_kg} kg", 20, (190, 210, 224)),
        (f"battery          {battery_pct} %", 20, (190, 210, 224)),
        ("ESC / close window to launch", 14, (120, 140, 155)),
    ]
    running = True
    while running:
        clock.tick(FPS)
        _state.dt = 1 / FPS
        running = _pump_events()
        screen.fill((8, 18, 28))
        pygame.draw.line(screen, (70, 110, 130), (60, 150), (WIDTH - 60, 150), 1)
        y = 90
        for text, size, color in lines:
            draw_text(screen, text, (80, y), size=size, color=color)
            y += size + 22
        _draw_snow(screen, Submarine(DEFAULT_DIVEPLAN))
        pygame.display.flip()
    pygame.quit()


def run(frame_fn, setup_fn=None, title="LUMEN - a descent"):
    """Open the game window and run the loop.  Every frame the engine draws the
    ocean, then calls YOUR frame_fn(sub, screen), then draws the sub, the
    darkness and the base HUD.  Anything you draw with draw_hud_text (or via
    draw_hull_status / draw_tick) is composited back on TOP of the darkness, so
    dashboard readouts never get swallowed by the dark, only the world outside
    your window does.  ESC or the window's close button quits."""
    if HEADLESS:
        return
    plan = load_diveplan()
    pygame.init()
    screen = pygame.display.set_mode((WIDTH, HEIGHT))
    pygame.display.set_caption(f"{title}   [engine {ENGINE_VERSION}]")
    _state.screen = screen
    clock = pygame.time.Clock()
    sub = Submarine(plan)
    if setup_fn is not None:
        setup_fn(sub)

    running = True
    while running:
        _state.dt = clock.tick(FPS) / 1000.0
        _state.t += _state.dt
        _state.frame += 1
        running = _pump_events()

        _update_systems(sub)
        _hud_surface().fill((0, 0, 0, 0))      # clear last frame's dashboard text

        _draw_background(screen, sub)
        _draw_snow(screen, sub)
        frame_fn(sub, screen)
        _draw_submarine(screen, sub)
        _draw_darkness(screen, sub)
        _draw_recharge_base(screen, sub)
        _draw_target_line(screen, sub)
        screen.blit(_state.hud_surface, (0, 0))    # dashboard on top - always visible
        _draw_base_hud(screen, sub)
        if not sub.alive:
            reason = "OXYGEN DEPLETED" if sub.oxygen <= 0 else "HULL BREACH"
