def save_diveplan(pilot, target_depth, ballast_kg, battery_pct, path="diveplan.json"):
    """Save the four dive-plan values to diveplan.json.  Values are stored
    exactly as you pass them in."""
    plan = {
        "pilot": pilot,
        "target_depth": target_depth,
        "ballast_kg": ballast_kg,
        "battery_pct": battery_pct,
    }
    with open(path, "w", encoding="utf-8") as f:
        json.dump(plan, f, indent=2)
    return plan


def load_diveplan(path="diveplan.json"):
    """Return the dive-plan dict.  Falls back to defaults if the file is
    missing or corrupt (you write that handling properly in Module 6)."""
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
    except (FileNotFoundError, ValueError, OSError):
        return dict(DEFAULT_DIVEPLAN)
    merged = dict(DEFAULT_DIVEPLAN)
    if isinstance(data, dict):
        merged.update(data)
    return merged


def _as_float(value, fallback):
    try:
        return float(value)
    except (TypeError, ValueError):
        return float(fallback)


# ---------------------------------------------------------------------------
# The submarine - a plain bag of values the engine keeps updated every frame.
# You read these (sub.depth, sub.oxygen, ...).  From Module 10 you rebuild it.
# ---------------------------------------------------------------------------
class Submarine:
    def __init__(self, plan):
        self.pilot = plan.get("pilot", "Unknown")
        self.depth = 0.0                                    # meters below surface
        self.x = 0.0                                        # horizontal drift
        self.target_depth = _as_float(plan.get("target_depth"), 300)
        # a circular recharge base somewhere in the world (not a single
        # exact point) - step within base_radius meters of (base_x,
        # base_depth), measuring straight-line distance so depth counts
        # too, and oxygen/power refill instead of draining. Module 5 gives
        # you a way to read how far the edge still is.
        self.base_x = random.choice((-1, 1)) * random.uniform(250.0, 900.0)
        self.base_depth = random.uniform(150.0, 700.0)
        self.base_radius = 120.0
        self.oxygen = 100.0                                 # percent
        self.power = _as_float(plan.get("battery_pct"), 100.0)   # percent
        self.ballast = _as_float(plan.get("ballast_kg"), 40.0)   # kg
        self.hull = 100.0                                   # integrity percent
        self.rated_depth = 1000.0                           # crush past here
        # heavier ballast sinks faster: 40 kg -> the old default of 20 m/s
        self.dive_rate = 8.0 + self.ballast * 0.3          # meters / second
        self.rise_rate = 24.0
        self.drift_speed = 24.0                            # meters / second, sideways - matches rise_rate
        self.total_drift = 0.0                             # meters drifted sideways, either direction, running total
        self.light_on = True
        self.light_radius = 155
        self.alive = True
        # one-frame request flags - main.py sets these, the engine consumes them
        self.descending = False
        self.ascending = False
        self.moving_left = False
        self.moving_right = False


